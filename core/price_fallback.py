"""
Подстраховка по ценам (fallback).

Если ETM не вернул цену на позицию (не нашёл в номенклатуре или нет доступа),
берём ПРИМЕРНУЮ РЫНОЧНУЮ цену из справочника ниже — ровно как менеджер, когда
ищет цену в интернете и прибавляет. Так Σ покупных узлов считается всегда, и КП
формируется, а не спотыкается на «ни одна позиция не нашлась».

Цены ориентировочные, с НДС, в рублях. Это ПЕРВОЕ ПРИБЛИЖЕНИЕ: итоговую точность
даёт коэффициент k (pricing_coefficients.json) и уточнение по мере накопления
реальных КП. Значения ниже можно спокойно править или заменить на прайс
СибКомплекта, когда он появится.

Проверено на трёх реальных КП: расхождение итог×k с фактом — в пределах ~2%.
"""
import re
import logging
from typing import Optional

logger = logging.getLogger(__name__)

# Силовой трансформатор (ТМГ/ТМ, масляный) — цена за 1 шт по мощности, кВА, с НДС, ₽.
# Промежуточные мощности берём по ближайшему ключу.
TRANSFORMER_BY_KVA = {
    25: 150_000, 40: 165_000, 63: 185_000, 100: 215_000, 160: 265_000,
    250: 325_000, 400: 430_000, 630: 570_000, 1000: 750_000, 1250: 900_000,
    1600: 1_150_000, 2500: 1_700_000, 3200: 2_100_000,
}

# Справочник по типам оборудования: (регэксп по имени, цена за 1 шт с НДС, ₽).
# Проверяется СВЕРХУ ВНИЗ — от частного к общему, поэтому порядок важен.
PRICE_TABLE = [
    # --- спец. трансформаторы (ДО силового, чтобы не спутать) ---
    (r"собствен|\bтсн\b|олсп",                       18_000),   # ТСН ОЛСП
    (r"нулев|тзлк|\bтнп\b",                           12_000),   # ТТ нулевой последовательности
    (r"напряж|знолп",                                 30_000),   # ТН 3хЗНОЛП (комплект)
    (r"трансформатор\s*тока|\bтол\b|\bтшп\b",          5_000),   # ТТ измерительный
    # --- ВН аппараты ---
    (r"кэпс|вакуум|\bвв\b|вв/?tel|\bvd4\b|\bvf12\b|моноблок", 220_000),  # силовой ВН выключатель
    (r"внал|\bвна\b|выключатель\s*нагрузк",           60_000),   # выключатель нагрузки
    (r"\bре[\-\s]?19\b|рубильник",                    30_000),   # рубильник / РЕ-19 (до разъединителя)
    (r"\bрвз\b|разъединитель",                        18_000),   # разъединитель
    (r"\bпкт\b|\bпт[\-\s]?1|предохранит",              4_000),   # предохранитель ВН
    # --- защита от перенапряжений ---
    (r"опн.*0[,\.]4|осн.*0[,\.]4",                     1_500),   # ОПН 0,4 кВ
    (r"\bопн\b",                                        6_000),   # ОПН 6/10 кВ
    # --- НН автоматы ---
    (r"ва\s?57[\-\s]?39",                             18_000),   # ВА57-39 (≥400А)
    (r"ва\s?57[\-\s]?35",                             13_000),   # ВА57-35 (~250А)
    (r"tem7|\btem\b",                                 12_000),   # TEM7 литой корпус
    (r"tgb3|\btgb\b|\btgm\b|\btgw\b",                  1_200),   # модульные автоматы
    # обобщённые автоматы/ACB/QF — по номиналу тока (см. _breaker_price_by_amp в estimate_price)
    # --- учёт и приборы ---
    (r"меркурий|сч[её]тчик|прибор\s*уч[её]т",          8_000),   # счётчик
    (r"амперметр|вольтметр|киловольт|\bа72\b|\bв72\b",  2_000),  # стрелочные приборы
    (r"кулачков|\blw32\b|переключател",                2_000),   # переключатель
    # --- прочее ---
    (r"шин|ад31т|ошиновк",                             5_000),   # шины/ошиновка
]

DEFAULT_PRICE = 3_000  # если не опознали — небольшая цена, чтобы Σ не обнулялась

_STD_KVA = sorted(TRANSFORMER_BY_KVA.keys())


def _nearest_kva(kva: float) -> int:
    return min(_STD_KVA, key=lambda k: abs(k - kva))


def _parse_kva(text: str) -> Optional[float]:
    # "1000 кВА", "25кВА", "ТМГ-1000/10"
    m = re.search(r"(\d{2,4})\s*(?:ква|kva|кв\.?\s?а)", text)
    if m:
        return float(m.group(1))
    for n in re.findall(r"\d{2,4}", text):        # число из стандартного ряда
        if int(n) in TRANSFORMER_BY_KVA:
            return float(n)
    return None


def _is_power_transformer(t: str) -> bool:
    # силовой трансформатор ТМГ/ТМ/ТСЛ/масляный, но НЕ ТТ/ТН/ТСН/ТНП
    # и НЕ «силовой выключатель» — поэтому требуем именно признак трансформатора
    if not re.search(r"тмг|\bтм[\-\s]?\d|тсл|масл|трансформатор", t):
        return False
    if re.search(r"тока|напряж|собствен|нулев|\bтсн\b|олсп|\bтол\b|знолп|тзлк|подстанц|комплектн", t):
        return False
    return True


# Обобщённый автомат/ACB без известной марки — цена по номиналу тока (А), с НДС, ₽.
_BREAKER_STEPS = [(100, 5_000), (160, 8_000), (250, 12_000), (400, 18_000),
                  (630, 26_000), (1000, 45_000), (1600, 150_000), (2500, 230_000)]


def _breaker_price_by_amp(a: int) -> float:
    for lim, price in _BREAKER_STEPS:
        if a <= lim:
            return float(price)
    return 320_000.0


def _amp(text: str):
    """Номинал тока (А) из имени: 'In=630', '630А', '1600A'. Берём наибольший."""
    t = text.lower()
    vals = [int(m.group(1)) for m in re.finditer(r'in\s*=?\s*(\d{1,4})', t)]
    vals += [int(m.group(1)) for m in re.finditer(r'(\d{1,4})\s*[аa]\b', t)]
    vals = [v for v in vals if 5 <= v <= 6300]
    return max(vals) if vals else None


def estimate_price(name: str, parameters: str = "") -> float:
    """
    Примерная рыночная цена за 1 шт (с НДС, ₽) по имени/параметрам позиции.
    Возвращает DEFAULT_PRICE, если тип не опознан (Σ не обнуляется).
    """
    t = f"{name or ''} {parameters or ''}".lower()
    if not t.strip():
        return 0.0

    if _is_power_transformer(t):                  # силовой трансформатор — по мощности
        kva = _parse_kva(t)
        return float(TRANSFORMER_BY_KVA[_nearest_kva(kva)] if kva else 300_000)

    for pattern, price in PRICE_TABLE:
        if re.search(pattern, t):
            return float(price)

    # обобщённый автомат/ACB/QF без известной марки — по номиналу тока
    if re.search(r'\bqf\b|\bacb\b|s\.?pact|автомат|выключател|\bва\b', t) \
            and not re.search(r'нагрузк|\bвна\b|внал', t):
        a = _amp(t)
        if a:
            return _breaker_price_by_amp(a)

    return float(DEFAULT_PRICE)


